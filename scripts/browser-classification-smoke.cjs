/* Use only a fresh disposable database with synthetic records. */
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const config=JSON.parse(fs.readFileSync(process.env.TALLY_BROWSER_CONFIG,'utf8'));
const screenshots=process.env.TALLY_SCREENSHOTS || path.resolve('.local/classification-screenshots');
fs.mkdirSync(screenshots,{recursive:true});
(async()=>{
  const browser=await chromium.launch({headless:true,channel:process.env.TALLY_BROWSER_CHANNEL || 'msedge'});
  const page=await browser.newPage({viewport:{width:1440,height:1000},locale:'zh-CN',timezoneId:'Asia/Shanghai'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const call=(url,body,method=body?'POST':'GET',expected=200)=>page.evaluate(async ({url,body,method,expected})=>{
    const r=await fetch(url,{method,headers:{'Content-Type':'application/json','X-Tally-Request':'1'},...(body?{body:JSON.stringify(body)}:{})});
    if(r.status!==expected)throw new Error(`${url}: ${r.status}, expected ${expected}`);
    return r.json();
  },{url,body,method,expected});
  const exported=async()=>(await call('/api/export')).entries;
  const entry=async id=>(await exported()).find(e=>e.id===id);
  async function saveRule(pattern,description,category){
    const form=page.locator('#rule-form');
    await form.locator('[name=pattern]').fill(pattern);
    await form.locator('[name=description_pattern]').fill(description);
    await form.locator('[name=category]').fill(category);
    await form.locator('#rule-save').click();
    await page.waitForFunction(()=>document.querySelector('#rule-form [name=category]')?.value==='');
  }
  async function view(){
    await page.locator('[data-tab=entries]').first().click();
    await page.locator('[data-tab=classification]').click();
    await page.locator('#classification-batch').waitFor();
  }
  try{
    await page.goto(config.base);
    await page.locator('#login-form [name=username]').fill(config.username);
    await page.locator('#login-form [name=password]').fill(config.password);
    await page.locator('#login-form button').click();
    await page.getByRole('heading',{name:'把日子，记得清楚。'}).waitFor();
    const base={date:'2026-07-10',kind:'expense',amount_cents:10000,merchant:'合成京东',description:'仅订单编号A',category:'待分类',account:'微信',note:'保留备注',split_start:null,split_months:null};
    const goods=(await call('/api/entries',base)).id;
    const meal=(await call('/api/entries',{...base,date:'2026-08-10',description:'仅订单编号B'})).id;
    const old=(await call('/api/entries',{...base,date:'2026-05-10',description:'游戏点卡',split_start:'2026-05',split_months:12,refunded_cents:500})).id;
    await call('/api/entries',{...base,merchant:'零元单车',amount_cents:0});
    await call('/api/entries',{...base,merchant:'全额退款',refunded_cents:10000});
    await call('/api/entries',{...base,merchant:'退款流水',kind:'refund',refund_of:null});
    await call('/api/entries',{...base,merchant:'账户转账',kind:'transfer'});
    const snapshot=await entry(meal);
    await view();
    assert.equal(await page.locator('.classification-table tbody tr').count(),3);
    await page.locator('[data-merchant-index]').filter({hasText:'合成京东'}).click();
    await page.locator(`[data-classification-id="${meal}"]`).check();
    await page.locator('#classification-batch [name=category]').fill('餐饮');
    await page.locator('#classification-save').click();
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('已整理 1 笔'));
    assert.equal((await entry(meal)).category,'餐饮');
    assert.equal((await entry(meal)).category_locked,true);
    assert.equal((await entry(goods)).category,'待分类');
    const after=await entry(meal);
    for(const key of Object.keys(snapshot).filter(k=>!['category','category_locked'].includes(k)))assert.deepEqual(after[key],snapshot[key]);
    await page.locator('[data-tab=settings]').first().click();
    await saveRule('合成京东','','日用购物');
    assert.equal((await entry(meal)).category,'餐饮');
    assert.equal((await entry(goods)).category,'日用购物');
    await saveRule('合成京东','游戏点卡','休闲娱乐');
    assert.equal((await entry(old)).category,'休闲娱乐');
    assert.equal((await call('/api/state')).rules.length,2);
    await page.locator('.rule-row').filter({hasText:'游戏点卡'}).locator('[data-edit-rule]').click();
    await page.locator('#rule-form [name=description_pattern]').fill('编号A');
    await page.locator('#rule-form [name=category]').fill('兴趣爱好');
    await page.locator('#rule-save').click();
    await page.waitForFunction(()=>document.querySelector('#rule-form [name=category]')?.value==='');
    assert.equal((await entry(old)).category,'日用购物');
    assert.equal((await entry(goods)).category,'兴趣爱好');
    assert.equal((await call('/api/state')).rules.length,2);
    await page.locator('[data-action=apply-rules]').click();
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('全部规则已应用'));
    assert.equal((await entry(meal)).category,'餐饮');
    page.once('dialog',d=>d.accept());
    await page.locator('.rule-row').filter({hasText:'编号A'}).locator('[data-delete-rule]').click();
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('规则已删除'));
    assert.equal((await entry(goods)).category,'日用购物');
    page.once('dialog',d=>d.accept());
    await page.locator('.rule-row').filter({hasText:'合成京东'}).locator('[data-delete-rule]').click();
    await page.waitForFunction(()=>document.querySelector('#rule-form') && !document.querySelector('[data-delete-rule]'));
    assert.equal((await entry(meal)).category,'餐饮');
    assert.equal((await entry(goods)).category,'待分类');
    await view();
    await page.locator('#classification-search [name=pending]').uncheck();
    await page.locator('#classification-search button').click();
    await page.locator(`[data-edit="${meal}"]`).click();
    assert.equal(await page.locator('#entry-form [name=category_locked]').isChecked(),true);
    await page.locator('#entry-form [name=category_locked]').uncheck();
    await page.locator('#entry-form button[type=submit]').click();
    await page.locator('#entry-dialog').waitFor({state:'hidden'});
    await call('/api/rules',{pattern:'合成京东',description_pattern:'',category:'日用购物',kind:'expense'});
    assert.equal((await entry(meal)).category,'日用购物');
    const before=await entry(goods);
    await call('/api/entries/categories',{ids:[goods,999999],category:'不应写入'},'POST',400);
    assert.deepEqual(await entry(goods),before);
    assert.equal((await call('/api/classification?pending=false&merchant=合成京东')).total,3);
    for(let i=0;i<51;i++)await call('/api/entries',{...base,merchant:'批量分页商户',description:`记录${i}`});
    await call('/api/entries',{...base,merchant:'合成京东商城'});
    await view();
    await page.locator('[data-merchant-index]').filter({hasText:'批量分页商户'}).click();
    await page.locator('#classification-select-page').check();
    assert.match(await page.locator('#classification-selected').innerText(),/50/);
    await page.locator('[data-action=classification-page][aria-label=下一页]').click();
    await page.locator('#classification-select-page').check();
    assert.match(await page.locator('#classification-selected').innerText(),/51/);
    await page.locator('#classification-batch [name=category]').fill('日用购物');
    await page.screenshot({path:path.join(screenshots,'classification-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:path.join(screenshots,'classification-mobile.png')});
    await page.locator('#classification-save').click();
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('已整理 51 笔'));
    assert.equal((await exported()).filter(e=>e.merchant==='批量分页商户' && e.category_locked).length,51);
    const noHeader=await page.evaluate(async()=>{const r=await fetch('/api/entries/categories',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({ids:[1],category:'餐饮'})});return r.status;});
    assert.equal(noHeader,403);
    await call('/api/logout',{},'POST');
    await call('/api/classification',null,'GET',401);
    await call('/api/entries/categories',{ids:[1],category:'餐饮'},'POST',401);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({status:'passed',flows:['cross-month-and-old-records','skip-zero-refund-transfer','exact-merchant-filter','selected-only-batch','preserve-fields','fixed-category','conditional-priority','edit-old-and-new-scope','delete-fallback','fixed-category-on-delete','unlock-entry','atomic-batch','cross-page-selection','mobile-layout','authentication-and-csrf'],screenshots}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
